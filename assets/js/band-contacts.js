(function () {
  function pluralize(count, singular, plural) {
    return count === 1 ? singular : plural;
  }

  function createEmailHref(band) {
    var subject = encodeURIComponent(band.name + ' contact');
    var bcc = encodeURIComponent(band.emails.join(','));
    return 'mailto:?bcc=' + bcc + '&subject=' + subject;
  }

  function renderBandContacts() {
    var mount = document.getElementById('band-state-list');
    if (!mount || !window.bandContactsByState) {
      return;
    }

    window.bandContactsByState.forEach(function (group) {
      var stateBlock = document.createElement('section');
      stateBlock.className = 'band-state-group';

      var heading = document.createElement('h3');
      heading.textContent = group.state;
      stateBlock.appendChild(heading);

      var list = document.createElement('ul');
      list.className = 'resource-list band-resource-list';

      group.bands.forEach(function (band) {
        var item = document.createElement('li');
        item.className = 'band-list-item';

        var details = document.createElement('div');
        details.className = 'band-list-details';

        var title = document.createElement('span');
        title.className = 'band-list-title';
        title.textContent = band.name;
        details.appendChild(title);

        var count = document.createElement('span');
        count.className = 'band-list-count';
        count.textContent = band.emails.length + ' ' + pluralize(band.emails.length, 'contact', 'contacts');
        details.appendChild(count);

        item.appendChild(details);

        var link = document.createElement('a');
        link.className = 'resource-link band-email-link';
        link.href = createEmailHref(band);
        link.innerHTML = '<i class="fa fa-envelope"></i><span>Email contacts</span>';
        item.appendChild(link);

        list.appendChild(item);
      });

      stateBlock.appendChild(list);
      mount.appendChild(stateBlock);
    });
  }

  function setupBandsToggle() {
    var toggle = document.getElementById('bands-toggle');
    var list = document.getElementById('band-state-list');
    if (!toggle || !list) {
      return;
    }

    toggle.addEventListener('click', function () {
      var isExpanded = toggle.getAttribute('aria-expanded') === 'true';
      toggle.setAttribute('aria-expanded', String(!isExpanded));
      list.hidden = isExpanded;
      list.classList.toggle('is-collapsed', isExpanded);
      toggle.querySelector('span').textContent = isExpanded ? 'Show Band Contacts' : 'Hide Band Contacts';
    });
  }

  function initBandContacts() {
    renderBandContacts();
    setupBandsToggle();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initBandContacts);
  } else {
    initBandContacts();
  }
}());
